package com.company.campaign.campaignagent;

import com.company.campaign.builder.campaignagent.CampaignAgentException;
import com.company.campaign.builder.campaignagent.http.CampaignAgentConversationHttpResponse;
import com.company.campaign.builder.campaignagent.http.CampaignAgentConversationService;
import com.company.campaign.builder.campaignagent.http.CampaignAgentHttpErrorCodes;
import com.company.campaign.conversation.CampaignConversationCreateKey;
import com.company.campaign.conversation.CampaignConversationIdentity;
import com.company.campaign.conversation.CampaignConversationIdentitySource;
import com.company.campaign.conversation.CampaignConversationKey;
import com.company.campaign.conversation.CampaignConversationReservation;
import com.company.campaign.conversation.CampaignConversationStore;
import com.company.campaign.conversation.ConversationStoreErrorCodes;
import com.company.campaign.conversation.ConversationStoreException;
import com.company.campaign.security.context.CampaignPermission;
import com.company.campaign.security.context.TrustedContextProvider;
import com.company.campaign.security.context.TrustedExecutionContext;
import com.company.campaign.shared.canonical.CanonicalJson;
import com.company.campaign.shared.canonical.ContentHash;

import java.util.LinkedHashMap;
import java.util.Objects;
import java.util.regex.Pattern;

/**
 * The neutral concrete {@link CampaignAgentConversationService} of this build.
 *
 * <p>Its constructor requires explicit host dependencies only — the trusted-context provider the turn boundary
 * uses, the conversation store and an injected narrow identity source. There is no thread-local, no global
 * security holder and no identity read from the request: the trusted context is resolved exactly once per call
 * through the shared host identity boundary, and the create is bound to the trusted tenant, program and user
 * that resolved it.
 *
 * <p>Every call requires an active membership and {@code campaign.edit} before anything is issued. The
 * identifiers are generated by the injected source — never by the caller and never from a raw user, tenant or
 * program value — and the identity is reserved atomically in the store. Collisions retry only through the
 * explicit bounded policy below and then fail closed with a stable code. A replay with the same idempotency key
 * returns the very same identity, and the same key with a different request fingerprint fails closed as a
 * conflict. The creation calls no routing model and no Tool.
 *
 * <p>It lives outside every {@code dev} package, so the production Campaign host wires it over the production
 * identity boundary and the durable conversation store; the development host keeps its clearly named subclass.
 */
public class CampaignConversationCreateService implements CampaignAgentConversationService {

    /** The explicit bound on how many distinct identities one create may try before failing closed. */
    public static final int MAX_IDENTITY_ATTEMPTS = 8;

    private static final Pattern IDEMPOTENCY_KEY = Pattern.compile("^[A-Za-z0-9][A-Za-z0-9._:-]{0,95}$");
    private static final CanonicalJson CANONICAL_JSON = new CanonicalJson();

    /**
     * The one canonical, value-free create request fingerprint: the strict empty JSON object.
     *
     * <p>A create request can carry no value at all, so every create shares this one fingerprint; only the
     * idempotency key distinguishes two creates. A host that reserves a conversation outside this service
     * (a test fixture, for example) uses the very same constant so the ledger is exercised identically.
     */
    public static final ContentHash CREATE_REQUEST_FINGERPRINT =
            ContentHash.sha256(CANONICAL_JSON.write(new LinkedHashMap<>()));

    private final TrustedContextProvider trustedContextProvider;
    private final CampaignConversationStore store;
    private final CampaignConversationIdentitySource identitySource;

    public CampaignConversationCreateService(
            TrustedContextProvider trustedContextProvider,
            CampaignConversationStore store,
            CampaignConversationIdentitySource identitySource) {
        this.trustedContextProvider = Objects.requireNonNull(trustedContextProvider, "trustedContextProvider");
        this.store = Objects.requireNonNull(store, "store");
        this.identitySource = Objects.requireNonNull(identitySource, "identitySource");
    }

    @Override
    public CampaignAgentConversationHttpResponse create(String idempotencyKey) {
        requireIdempotencyKey(idempotencyKey);
        TrustedExecutionContext context = resolveContext();
        requirePermission(context, CampaignPermission.CAMPAIGN_EDIT);
        CampaignConversationCreateKey createKey = new CampaignConversationCreateKey(
                context.tenantId(), context.programId(), context.userId(), idempotencyKey);
        for (int attempt = 0; attempt < MAX_IDENTITY_ATTEMPTS; attempt++) {
            CampaignConversationIdentity identity = identitySource.next();
            CampaignConversationKey requested = new CampaignConversationKey(
                    context.tenantId(), context.programId(), context.userId(),
                    identity.conversationId(), identity.runId());
            try {
                CampaignConversationReservation reservation =
                        store.reserve(createKey, requested, CREATE_REQUEST_FINGERPRINT);
                return new CampaignAgentConversationHttpResponse(
                        reservation.conversationId(), reservation.runId(), reservation.revision());
            } catch (ConversationStoreException failure) {
                if (ConversationStoreErrorCodes.IDENTITY_COLLISION.equals(failure.code())) {
                    // The explicit bounded retry: mint a distinct identity, then try again, never reuse one.
                    continue;
                }
                throw bounded(failure.code());
            }
        }
        throw CampaignAgentException.of(
                CampaignAgentHttpErrorCodes.CREATE_IDENTITY_EXHAUSTED,
                "The host could not issue a distinct conversation identity within its bounded retry policy.");
    }

    /** Maps one bounded store failure onto the one stable HTTP code that describes it, without any value. */
    private static CampaignAgentException bounded(String storeCode) {
        if (ConversationStoreErrorCodes.CREATE_CONFLICT.equals(storeCode)) {
            return CampaignAgentException.of(
                    CampaignAgentHttpErrorCodes.CONFLICT,
                    "The create Idempotency-Key was already used for a different request.");
        }
        if (ConversationStoreErrorCodes.STORE_CAPACITY_EXCEEDED.equals(storeCode)) {
            return CampaignAgentException.of(
                    CampaignAgentHttpErrorCodes.SERVICE_UNAVAILABLE,
                    "The conversation registry is at its bounded capacity.");
        }
        return CampaignAgentException.of(
                CampaignAgentHttpErrorCodes.INTERNAL_FAILURE,
                "The conversation identity could not be reserved.");
    }

    // ------------------------------------------------------------------ trusted boundary

    private TrustedExecutionContext resolveContext() {
        TrustedExecutionContext context;
        try {
            context = trustedContextProvider.trustedContext();
        } catch (CampaignAgentException failure) {
            throw failure;
        } catch (RuntimeException failure) {
            throw CampaignAgentException.of(
                    CampaignAgentHttpErrorCodes.UNAUTHENTICATED, "No trusted identity could be resolved.");
        }
        if (context == null || !context.membership().isActive()) {
            throw CampaignAgentException.of(
                    CampaignAgentHttpErrorCodes.UNAUTHENTICATED, "No active trusted identity could be resolved.");
        }
        return context;
    }

    private static void requirePermission(TrustedExecutionContext context, CampaignPermission permission) {
        if (!context.hasPermission(permission)) {
            throw CampaignAgentException.of(
                    CampaignAgentHttpErrorCodes.FORBIDDEN,
                    "The trusted identity does not hold the permission a conversation create requires.");
        }
    }

    private static void requireIdempotencyKey(String idempotencyKey) {
        if (idempotencyKey == null || idempotencyKey.isEmpty()) {
            throw CampaignAgentException.of(
                    CampaignAgentHttpErrorCodes.IDEMPOTENCY_KEY_REQUIRED,
                    "Every Campaign conversation create requires a bounded Idempotency-Key.");
        }
        if (idempotencyKey.length() > CampaignConversationCreateKey.MAX_IDEMPOTENCY_KEY_LENGTH
                || !IDEMPOTENCY_KEY.matcher(idempotencyKey).matches()) {
            throw CampaignAgentException.of(
                    CampaignAgentHttpErrorCodes.IDEMPOTENCY_KEY_INVALID,
                    "The Idempotency-Key is malformed or over its declared bound.");
        }
    }

    /** A bounded diagnostic: the wiring facts only, never a value. */
    @Override
    public String toString() {
        return "CampaignConversationCreateService[serverOwnedIdentity=true]";
    }
}