-- T25 readiness slice, migration 3 of 3.
--
-- Expand-only: it adds the immutable audit trail. A readiness evidence write, an assessment and their audit
-- rows are committed in one transaction, so a rolled-back unit leaves no audit row claiming a write that
-- never happened.
--
-- The audit table has no column for an evidence payload, a credential, a member identifier, a recipient or
-- Provider target, model prose or a raw failure: redaction is a property of the schema, not a rule an author
-- has to remember. The evidence subject is reduced to a non-reversible fingerprint before it is stored.

CREATE TABLE IF NOT EXISTS readiness_audit (
    audit_id              BIGINT GENERATED BY DEFAULT AS IDENTITY,
    tenant_id             VARCHAR(128) NOT NULL,
    program_id            VARCHAR(128) NOT NULL,
    environment           VARCHAR(32)  NOT NULL,
    format_version        VARCHAR(64)  NOT NULL,
    action                VARCHAR(32)  NOT NULL,
    disposition           VARCHAR(32)  NOT NULL,
    reason_code           VARCHAR(64),
    occurred_at           TIMESTAMP WITH TIME ZONE NOT NULL,
    actor_ref             VARCHAR(128) NOT NULL,
    request_correlation   VARCHAR(128) NOT NULL,
    requirement_code      VARCHAR(64),
    status_transition     VARCHAR(64),
    evidence_identity_hash VARCHAR(80),
    subject_fingerprint   VARCHAR(80),
    assessment_hash       VARCHAR(80),
    committed_revision    BIGINT       NOT NULL,
    CONSTRAINT pk_readiness_audit PRIMARY KEY (audit_id),
    CONSTRAINT ck_readiness_audit_action
        CHECK (action IN ('RECORD_EVIDENCE', 'EVALUATE_READINESS')),
    CONSTRAINT ck_readiness_audit_disposition
        CHECK (disposition IN ('RECORDED', 'DUPLICATE', 'CONFLICT', 'STALE_REVISION', 'REJECTED')),
    CONSTRAINT ck_readiness_audit_revision CHECK (committed_revision >= 0)
);

CREATE INDEX IF NOT EXISTS ix_readiness_audit_scope
    ON readiness_audit (tenant_id, program_id, environment, audit_id);