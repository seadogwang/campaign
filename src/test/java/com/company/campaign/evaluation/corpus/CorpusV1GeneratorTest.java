package com.company.campaign.evaluation.corpus;

import com.company.campaign.evaluation.segment.contract.CaseReviewEntry;
import com.company.campaign.evaluation.segment.contract.CaseReviewEvidence;
import com.company.campaign.evaluation.segment.contract.ReviewStatus;
import com.company.campaign.shared.canonical.CanonicalJson;
import org.junit.jupiter.api.Assumptions;
import org.junit.jupiter.api.Test;
import org.junit.jupiter.api.io.TempDir;

import java.io.IOException;
import java.io.UncheckedIOException;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.Map;

import static org.assertj.core.api.Assertions.assertThat;
import static org.assertj.core.api.Assertions.assertThatThrownBy;

/**
 * Determinism and maintenance guarantees of the candidate corpus generator.
 *
 * <p>The committed corpus is source evidence: the default test only compares the generated bytes with the
 * committed bytes and never rewrites the source tree. Regeneration is an explicit, opt-in command.
 */
class CorpusV1GeneratorTest {

    private static final CanonicalJson CANONICAL_JSON = new CanonicalJson();

    @TempDir
    Path temporaryRoot;

    @Test
    void generatedAssetsAreByteIdenticalAcrossRuns() {
        Map<String, byte[]> first = CorpusV1Generator.generate();
        Map<String, byte[]> second = CorpusV1Generator.generate();

        assertThat(first.keySet()).isEqualTo(second.keySet());
        for (String path : first.keySet()) {
            assertThat(first.get(path)).as("asset %s", path).isEqualTo(second.get(path));
        }
        assertThat(first).hasSizeGreaterThan(225);
    }

    @Test
    void committedCorpusIsExactlyTheGeneratedCorpus() {
        Map<String, byte[]> generated = CorpusV1Generator.generate();

        assertThat(CorpusV1Generator.differences(repositoryRoot(), generated))
                .as("committed corpus differs from generated bytes; run the documented regeneration command")
                .isEmpty();
    }

    @Test
    void noCommittedReviewLedgerCarriesADecision() throws IOException {
        Path reviews = CorpusV1Generator.corpusRoot(repositoryRoot()).resolve("reviews");
        assertThat(reviews).isDirectory();

        int ledgers = 0;
        try (var stream = Files.list(reviews)) {
            for (Path file : stream.filter(path -> path.toString().endsWith(".json")).toList()) {
                CaseReviewEvidence review = CANONICAL_JSON.read(
                        Files.readString(file, StandardCharsets.UTF_8), CaseReviewEvidence.class);
                review.requireValidContentHash();
                for (CaseReviewEntry entry : review.reviews()) {
                    assertThat(entry.status())
                            .as("committed review %s for role %s", file.getFileName(), entry.role())
                            .isEqualTo(ReviewStatus.PENDING);
                }
                ledgers++;
            }
        }
        assertThat(ledgers).isEqualTo(225);
    }

    @Test
    void regenerationWritesOnlyWhenExplicitlyRequested() {
        Assumptions.assumeTrue(Boolean.getBoolean(CorpusV1Generator.REGENERATE_PROPERTY),
                "set -D" + CorpusV1Generator.REGENERATE_PROPERTY + "=true to regenerate the committed corpus");

        Map<String, byte[]> generated = CorpusV1Generator.generate();
        CorpusV1Generator.write(repositoryRoot(), generated);

        assertThat(CorpusV1Generator.differences(repositoryRoot(), generated)).isEmpty();
    }

    @Test
    void generatorRefusesToOverwriteADecidedReviewLedger() throws IOException {
        Map<String, byte[]> generated = CorpusV1Generator.generate();
        CorpusV1Generator.write(temporaryRoot, generated);

        Path reviews = CorpusV1Generator.corpusRoot(temporaryRoot).resolve("reviews");
        Path ledger = Files.list(reviews).filter(path -> path.toString().endsWith(".json")).findFirst().orElseThrow();
        CaseReviewEvidence pending = CANONICAL_JSON.read(
                Files.readString(ledger, StandardCharsets.UTF_8), CaseReviewEvidence.class);
        CaseReviewEvidence approved = pending.withReviewHash(null);
        CaseReviewEntry approvedProduct = CaseReviewEntry.decided(
                com.company.campaign.evaluation.segment.contract.ReviewRole.PRODUCT, ReviewStatus.APPROVED,
                "reviewer-product-01", "review-evidence-product-001",
                java.time.Instant.parse("2026-10-01T03:00:00Z"), "Approved by a real owner.");
        CaseReviewEvidence decided = CaseReviewEvidence.of(
                approved.schemaVersion(), approved.caseId(), approved.caseHash(), approved.expectedHash(),
                java.util.List.of(approvedProduct, approved.reviews().get(1), approved.reviews().get(2)));
        write(ledger, CANONICAL_JSON.write(decided));

        assertThatThrownBy(() -> CorpusV1Generator.write(temporaryRoot, generated))
                .isInstanceOf(IllegalStateException.class)
                .hasMessageContaining("Refusing to regenerate");
    }

    @Test
    void generatorCountsMatchTheRequiredCorpus() {
        Map<String, Integer> counts = CorpusV1Generator.countsByDirectory(CorpusV1Generator.generate());
        assertThat(counts).containsEntry("cases", 225);
        assertThat(counts).containsEntry("expected", 225);
        assertThat(counts).containsEntry("reviews", 225);
    }

    private static Path repositoryRoot() {
        return Path.of("");
    }

    private static void write(Path file, byte[] bytes) {
        try {
            Files.write(file, bytes);
        } catch (IOException exception) {
            throw new UncheckedIOException(exception);
        }
    }
}