package com.company.campaign.evaluation.segment.reference.testsupport;

import com.company.campaign.evaluation.segment.contract.CaseReviewEntry;
import com.company.campaign.evaluation.segment.contract.CaseReviewEvidence;
import com.company.campaign.evaluation.segment.contract.ReviewRole;
import com.company.campaign.evaluation.segment.contract.ReviewStatus;
import com.company.campaign.evaluation.segment.reference.ReferenceCorpusVersions;
import com.company.campaign.shared.canonical.CanonicalJson;
import org.junit.jupiter.api.Assumptions;
import org.junit.jupiter.api.Test;
import org.junit.jupiter.api.io.TempDir;

import java.io.IOException;
import java.io.UncheckedIOException;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.time.Instant;
import java.util.List;
import java.util.Map;

import static org.assertj.core.api.Assertions.assertThat;
import static org.assertj.core.api.Assertions.assertThatThrownBy;

/**
 * Determinism and maintenance guarantees of the committed reference corpus generator.
 *
 * <p>The committed corpus is source evidence: the default test only compares the generated bytes with the
 * committed bytes and never rewrites the source tree. Regeneration is an explicit, opt-in command.
 */
class ReferenceCorpusV1GeneratorTest {

    private static final CanonicalJson CANONICAL_JSON = new CanonicalJson();

    @TempDir
    Path temporaryRoot;

    @Test
    void generatedAssetsAreByteIdenticalAcrossRuns() {
        Map<String, byte[]> first = ReferenceCorpusV1Generator.generate();
        Map<String, byte[]> second = ReferenceCorpusV1Generator.generate();

        assertThat(first.keySet()).isEqualTo(second.keySet());
        for (String path : first.keySet()) {
            assertThat(first.get(path)).as("asset %s", path).isEqualTo(second.get(path));
        }
        assertThat(first).hasSizeGreaterThan(100);
    }

    @Test
    void committedCorpusIsExactlyTheGeneratedCorpus() {
        Map<String, byte[]> generated = ReferenceCorpusV1Generator.generate();

        assertThat(ReferenceCorpusV1Generator.differences(repositoryRoot(), generated))
                .as("committed corpus differs from generated bytes; run the documented regeneration command")
                .isEmpty();
    }

    @Test
    void noCommittedReviewLedgerCarriesADecision() throws IOException {
        Path reviews = ReferenceCorpusV1Generator.corpusRoot(repositoryRoot()).resolve("reviews");
        assertThat(reviews).isDirectory();

        int ledgerCount = 0;
        try (var stream = Files.list(reviews)) {
            for (Path file : stream.filter(path -> path.toString().endsWith(".json")).toList()) {
                CaseReviewEvidence review = CANONICAL_JSON.read(
                        Files.readString(file, StandardCharsets.UTF_8), CaseReviewEvidence.class);
                review.requireValidContentHash();
                for (CaseReviewEntry entry : review.reviews()) {
                    assertThat(entry.status())
                            .as("committed review %s for role %s", file.getFileName(), entry.role())
                            .isEqualTo(ReviewStatus.PENDING);
                }
                ledgerCount++;
            }
        }
        assertThat(ledgerCount).isEqualTo(ReferenceCorpusBlueprints.cases().size());
    }

    @Test
    void regenerationWritesOnlyWhenExplicitlyRequested() {
        Assumptions.assumeTrue(Boolean.getBoolean(ReferenceCorpusV1Generator.REGENERATE_PROPERTY),
                "set -D" + ReferenceCorpusV1Generator.REGENERATE_PROPERTY
                        + "=true to regenerate the committed reference corpus");

        Map<String, byte[]> generated = ReferenceCorpusV1Generator.generate();
        ReferenceCorpusV1Generator.write(repositoryRoot(), generated);

        assertThat(ReferenceCorpusV1Generator.differences(repositoryRoot(), generated)).isEmpty();
    }

    @Test
    void generatorRefusesToOverwriteADecidedReviewLedger() throws IOException {
        Map<String, byte[]> generated = ReferenceCorpusV1Generator.generate();
        ReferenceCorpusV1Generator.write(temporaryRoot, generated);

        Path reviews = ReferenceCorpusV1Generator.corpusRoot(temporaryRoot).resolve("reviews");
        Path ledger = Files.list(reviews)
                .filter(path -> path.toString().endsWith(".json"))
                .findFirst()
                .orElseThrow();
        CaseReviewEvidence pending = CANONICAL_JSON.read(
                Files.readString(ledger, StandardCharsets.UTF_8), CaseReviewEvidence.class);
        CaseReviewEntry approvedProduct = CaseReviewEntry.decided(
                ReviewRole.PRODUCT, ReviewStatus.APPROVED, "owner-product-1", "review-evidence-product-001",
                Instant.parse("2026-10-07T09:00:00Z"), "Approved by a real owner.");
        CaseReviewEvidence decided = CaseReviewEvidence.of(
                pending.schemaVersion(), pending.caseId(), pending.caseHash(), pending.expectedHash(),
                List.of(approvedProduct, pending.reviews().get(1), pending.reviews().get(2)));
        write(ledger, CANONICAL_JSON.write(decided));

        assertThatThrownBy(() -> ReferenceCorpusV1Generator.write(temporaryRoot, generated))
                .isInstanceOf(IllegalStateException.class)
                .hasMessageContaining("Refusing to regenerate");
    }

    @Test
    void generatorCountsMatchTheReviewedBlueprints() {
        int cases = ReferenceCorpusBlueprints.cases().size();
        int fixtures = ReferenceCorpusBlueprints.fixtures().size();

        Map<String, Integer> counts =
                ReferenceCorpusV1Generator.countsByDirectory(ReferenceCorpusV1Generator.generate());

        assertThat(counts)
                .containsEntry("cases", cases)
                .containsEntry("expected", cases)
                .containsEntry("reviews", cases)
                .containsEntry("fixtures", fixtures + 1)
                .containsEntry("(root)", 2);
        assertThat(cases).isGreaterThanOrEqualTo(ReferenceCorpusVersions.GATE_MINIMUM_CASES);
    }

    private static Path repositoryRoot() {
        return Path.of("");
    }

    private static void write(Path file, byte[] bytes) {
        try {
            Files.write(file, bytes);
        } catch (IOException exception) {
            throw new UncheckedIOException(exception);
        }
    }
}